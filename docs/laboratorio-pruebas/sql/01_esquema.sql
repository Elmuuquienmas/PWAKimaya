-- Esquema del laboratorio (PostgreSQL 17 / Supabase).
-- La API corre con ddl-auto=validate, asi que estas tablas deben existir antes de levantarla.

create table if not exists public.game_sessions (
  id bigint generated by default as identity primary key,
  player_name text,
  device_info text,
  connected_at timestamp
);

create table if not exists public.command_logs (
  id bigint generated by default as identity primary key,
  game_session_id bigint references public.game_sessions(id),
  action_type text,
  payload text,
  executed_at timestamp
);
